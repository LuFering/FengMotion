/* 与 StartCreation 同口径：首行过短 / 只有数字标点时不直接当名字 */
export function usableName(text: string): string {
  const first = text.trim().split('\n')[0] ?? ''
  return first.length >= 2 && !/^[\d\s\p{P}]+$/u.test(first) ? first : ''
}

